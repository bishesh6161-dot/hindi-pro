import express from 'express';
import cors from 'cors';
import anime from './routes/anime.js';
import yume from './routes/yume.js';
const app=express();
app.use(cors());app.use(express.json({limit:'1mb'}));
app.get('/',(req,res)=>res.json({name:'YumeZone Scraper API',version:'1.0.0',endpoints:['/api/home','/api/search?keyword=naruto','/api/info?id=20','/api/episodes?id=20','/api/watch?id=20&ep=2','/api/servers?id=20&ep=2','POST /api/extract','POST /api/parse-hls']}));
app.use('/api',anime);app.use('/api',yume);
app.use((err,req,res,next)=>res.status(500).json({success:false,error:err.message||'Internal server error'}));
const port=3000;
app.listen(port,()=>console.log(`YumeZone scraper listening on http://localhost:${port}`));
